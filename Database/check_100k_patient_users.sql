PROMPT ===== 5. Mapping problems =====
SELECT 'PATIENT_WITHOUT_ORACLE_USER' AS CHECK_NAME,
       TO_CHAR(COUNT(*)) AS CHECK_VALUE
FROM BVDBA.BENHNHAN B
WHERE REGEXP_LIKE(B.MABN, '^BN[0-9]{6}$')
  AND B.MABN BETWEEN 'BN000001' AND 'BN100000'
  AND B.TENBN LIKE N'[TEST100K]%'
  AND NOT EXISTS (
      SELECT 1 FROM DBA_USERS U WHERE U.USERNAME = B.ORACLE_USERNAME
  )
UNION ALL
SELECT 'USER_WITHOUT_PATIENT_ROW',
       TO_CHAR(COUNT(*))
FROM DBA_USERS U
WHERE REGEXP_LIKE(U.USERNAME, '^BN[0-9]{6}$')
  AND U.USERNAME BETWEEN 'BN000001' AND 'BN100000'
  AND NOT EXISTS (
      SELECT 1
      FROM BVDBA.BENHNHAN B
      WHERE B.ORACLE_USERNAME = U.USERNAME
        AND B.MABN = U.USERNAME
        AND B.TENBN LIKE N'[TEST100K]%'
  )
UNION ALL
SELECT 'USER_WITHOUT_PATIENT_ROLE',
       TO_CHAR(COUNT(*))
FROM DBA_USERS U
WHERE REGEXP_LIKE(U.USERNAME, '^BN[0-9]{6}$')
  AND U.USERNAME BETWEEN 'BN000001' AND 'BN100000'
  AND NOT EXISTS (
      SELECT 1
      FROM DBA_ROLE_PRIVS RP
      WHERE RP.GRANTEE = U.USERNAME
        AND RP.GRANTED_ROLE IN ('RL_BENHNHAN', 'ROLE_BENHNHAN_DEMO')
  );

