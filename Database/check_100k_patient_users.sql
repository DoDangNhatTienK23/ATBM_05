COLUMN CHECK_VALUE FORMAT A30;
COLUMN USERNAME FORMAT A16;
COLUMN ACCOUNT_STATUS FORMAT A20;
COLUMN GRANTED_ROLE FORMAT A24;
COLUMN MABN FORMAT A12;
COLUMN TENBN FORMAT A34;
COLUMN ORACLE_USERNAME FORMAT A18;
COLUMN ROLE_STATUS FORMAT A14;
COLUMN PATIENT_STATUS FORMAT A14;

PROMPT ===== 1. Count generated Oracle users =====
SELECT 'GENERATED_ORACLE_USERS' AS CHECK_NAME,
       TO_CHAR(COUNT(*)) AS CHECK_VALUE
FROM DBA_USERS
WHERE REGEXP_LIKE(USERNAME, '^BN[0-9]{6}$')
  AND USERNAME BETWEEN 'BN000001' AND 'BN100000';

