PROMPT ===== 2. Count generated patient rows with safe marker =====
SELECT 'GENERATED_PATIENT_ROWS' AS CHECK_NAME,
       TO_CHAR(COUNT(*)) AS CHECK_VALUE
FROM BVDBA.BENHNHAN
WHERE REGEXP_LIKE(MABN, '^BN[0-9]{6}$')
  AND MABN BETWEEN 'BN000001' AND 'BN100000'
  AND ORACLE_USERNAME = MABN
  AND CCCD = '9' || LPAD(TO_NUMBER(SUBSTR(MABN, 3)), 11, '0')
  AND TENBN LIKE N'[TEST100K]%';

