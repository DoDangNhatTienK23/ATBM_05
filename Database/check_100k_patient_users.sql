PROMPT ===== 4. Sample patient mapping =====
SELECT B.MABN,
       B.TENBN,
       B.CCCD,
       B.ORACLE_USERNAME,
       CASE
           WHEN U.USERNAME IS NOT NULL THEN 'USER_OK'
           ELSE 'NO_USER'
       END AS USER_STATUS,
       CASE
           WHEN RP.GRANTED_ROLE IS NOT NULL THEN 'ROLE_OK'
           ELSE 'NO_ROLE'
       END AS ROLE_STATUS
FROM BVDBA.BENHNHAN B
LEFT JOIN DBA_USERS U
       ON U.USERNAME = B.ORACLE_USERNAME
LEFT JOIN DBA_ROLE_PRIVS RP
       ON RP.GRANTEE = B.ORACLE_USERNAME
      AND RP.GRANTED_ROLE IN ('RL_BENHNHAN', 'ROLE_BENHNHAN_DEMO')
WHERE B.MABN IN ('BN000001', 'BN000100', 'BN001000', 'BN010000', 'BN100000')
ORDER BY B.MABN;

