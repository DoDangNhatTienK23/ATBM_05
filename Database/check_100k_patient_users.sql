PROMPT ===== 3. Sample users =====
SELECT U.USERNAME,
       U.ACCOUNT_STATUS,
       CASE WHEN RP.GRANTED_ROLE IS NOT NULL THEN RP.GRANTED_ROLE ELSE '(NO PATIENT ROLE)' END AS GRANTED_ROLE
FROM (
    SELECT 'BN000001' USERNAME FROM DUAL UNION ALL
    SELECT 'BN000100' FROM DUAL UNION ALL
    SELECT 'BN001000' FROM DUAL UNION ALL
    SELECT 'BN010000' FROM DUAL UNION ALL
    SELECT 'BN100000' FROM DUAL
) S
LEFT JOIN DBA_USERS U
       ON U.USERNAME = S.USERNAME
LEFT JOIN DBA_ROLE_PRIVS RP
       ON RP.GRANTEE = S.USERNAME
      AND RP.GRANTED_ROLE IN ('RL_BENHNHAN', 'ROLE_BENHNHAN_DEMO')
ORDER BY S.USERNAME;

